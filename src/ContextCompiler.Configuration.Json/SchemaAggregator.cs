using System.Text.Json;
using System.Text.Json.Nodes;

using ContextCompiler.Abstractions.Configuration;

namespace ContextCompiler.Configuration.Json;

internal sealed class SchemaAggregator : IConfigurationSchemaAggregator
{

    public bool CanAggregate(ISchema schema)
    {
        return Path.GetExtension(schema.Path) == ".json";
    }

    public static JsonObject LoadJsonObject(ISchema schema)
    {
        JsonNode? node = JsonNode.Parse(schema.Content);
        return node as JsonObject ?? [];
    }

    public Task<IAggregatedSchema> Aggregate(ISchema schema1, ISchema schema2)
    {
        JsonObject root = LoadJsonObject(schema1);

        JsonObject defs = root["$defs"] as JsonObject ?? [];
        root["$defs"] = defs;

        List<string> defNames = [];
        JsonObject plugin = LoadJsonObject(schema2);
        string defName = MakeSafeDefName(schema2, plugin);

        JsonObject rewritten = RewritePluginSchemaForEmbedding(plugin, defName);
        defs[defName] = rewritten;
        defNames.Add(defName);

        MergePluginOptionsDefIfPresent(root, rewritten, defName);

        if (defNames.Count > 0)
        {
            ApplyFilesOptionsOneOf(root, defNames);
        }

        root["$comment"] = "Generated by ctxc plugins restore. Aggregates core schema + plugin schemas.";

        return Task.FromResult<IAggregatedSchema>(new JsonAggregatedSchema()
        {
            Content = root.ToJsonString(new JsonSerializerOptions { WriteIndented = true }),
            Name = $"{Path.GetFileNameWithoutExtension(schema1.Name)}_Aggregated",
            Path = schema1.Path
        });
    }

    private static void MergePluginOptionsDefIfPresent(JsonObject root, JsonObject pluginSchema, string pluginDefName)
