    private static string DerivePluginKey(JsonObject pluginSchema)
    {
        if (pluginSchema["$defs"] is JsonObject defs
            && defs["pluginMeta"] is JsonObject meta
            && meta["properties"] is JsonObject props
            && props["pluginKey"] is JsonObject pluginKeySchema)
        {
            string? key = pluginKeySchema["const"]?.GetValue<string?>();
            if (!string.IsNullOrWhiteSpace(key))
            {
                return key;
            }

            if (pluginKeySchema["enum"] is JsonArray arr && arr.Count > 0)
            {
                string? enumKey = arr[0]?.GetValue<string?>();
                if (!string.IsNullOrWhiteSpace(enumKey))
                {
                    return enumKey;
                }
            }
        }

        throw new InvalidOperationException("Plugin schema missing $defs.pluginMeta.pluginKey");
    }

    private static JsonObject ExtractPluginExtractItemSchema(JsonObject pluginProvidedOptions)
    {
        if (pluginProvidedOptions["properties"] is not JsonObject props)
        {
            return pluginProvidedOptions;
        }

        if (props["extracts"] is not JsonObject extracts)
        {
            return pluginProvidedOptions;
        }

        if (extracts["items"] is not JsonObject items)
        {
            return pluginProvidedOptions;
        }

        // If items is already a schema object, return it. (If plugin uses array schema with oneOf inside, it can still work.)
        return items;
    }

    private static JsonObject RewritePluginSchemaForEmbedding(JsonObject pluginSchema, string pluginDefName)
    {
        JsonNode clone = pluginSchema.DeepClone();
        RewriteRefsRecursive(clone, pluginDefName);
        return clone as JsonObject ?? [];
    }

    private static void RewriteRefsRecursive(JsonNode node, string pluginDefName)
    {
        if (node is JsonObject obj)
        {
            foreach ((string key, JsonNode? value) in obj.ToList())
            {
                if (key == "$ref" && value is JsonValue v)
                {
                    string? s = v.GetValue<string?>();
                    if (TryRewritePluginLocalRef(s, pluginDefName, out string? rewritten))
                    {
                        obj[key] = rewritten;
                    }
                    continue;
                }

                if (value is not null)
                {
                    RewriteRefsRecursive(value, pluginDefName);
                }
            }
        }
        else if (node is JsonArray arr)
        {
            foreach (JsonNode? item in arr)
            {
                if (item is not null)
                {
                    RewriteRefsRecursive(item, pluginDefName);
                }
            }
        }
    }

    private static bool TryRewritePluginLocalRef(string? refValue, string pluginDefName, out string? rewritten)
    {
        rewritten = null;
        if (string.IsNullOrWhiteSpace(refValue))
        {
            return false;
        }

        const string prefix = "#/$defs/";
        if (!refValue.StartsWith(prefix, StringComparison.Ordinal))
        {
            return false;
        }

        string alreadyPrefixed = $"#/$defs/{pluginDefName}/";
        if (refValue.StartsWith(alreadyPrefixed, StringComparison.Ordinal))
        {
            return false;
        }

        // The plugin schema is embedded under `#/$defs/<pluginDefName>`.
        // Rewrite `#/$defs/x` -> `#/$defs/<pluginDefName>/$defs/x`.
        rewritten = $"#/$defs/{pluginDefName}/$defs/{refValue[prefix.Length..]}";
        return true;
    }

    private static void ApplyFilesOptionsOneOf(JsonObject root, List<string> defNames)
    {
        JsonObject? properties = root["properties"] as JsonObject;
        JsonObject? files = properties?["files"] as JsonObject;
        JsonObject? items = files?["items"] as JsonObject;
        JsonObject? fileProps = items?["properties"] as JsonObject;
        if (fileProps?["options"] is not JsonObject options)
        {
            return;
        }

        JsonArray oneOf = [];

        // allow empty/unspecified options
        oneOf.Add(new JsonObject
        {
            ["type"] = "object",
            ["additionalProperties"] = true
        });

        foreach (string defName in defNames.OrderBy(n => n, StringComparer.OrdinalIgnoreCase))
        {
            oneOf.Add(new JsonObject { ["$ref"] = $"#/$defs/{defName}" });
        }

        options["oneOf"] = oneOf;
        _ = options.Remove("additionalProperties");
    }

    public static string MakeSafeDefName(ISchema schema, JsonObject pluginSchema)
    {
        string? id = pluginSchema["$id"]?.GetValue<string?>();
        return !string.IsNullOrWhiteSpace(id)
            ? Sanitize(id)
            : Sanitize(Path.GetFileNameWithoutExtension(schema.Path));
    }

    private static string Sanitize(string s)
    {
        Span<char> buf = stackalloc char[s.Length];
        int j = 0;
        foreach (char c in s)
        {
            buf[j++] = char.IsLetterOrDigit(c) ? c : '_';
        }
        return new string(buf[..j]);
    }

    public static void Write(JsonObject schema, string path)
    {
        _ = Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, schema.ToJsonString(new JsonSerializerOptions { WriteIndented = true }));
    }
}
