              .AppendLine("        .timestamp {")
              .AppendLine("            color: #666;")
              .AppendLine("            font-size: 0.9em;")
              .AppendLine("            margin-top: 20px;")
              .AppendLine("        }")
              .AppendLine("    </style>")
              .AppendLine("</head>")
              .AppendLine("<body>")
              .AppendLine("    <div class=\"container\">")
              .AppendLine(CultureInfo.InvariantCulture, $"        <h1>{title}</h1>")
              .AppendLine("        <div class=\"mermaid\">")
              .AppendLine(mermaidDiagram)
              .AppendLine("        </div>")
              .AppendLine("        <div class=\"legend\">")
              .AppendLine("            <h3>Legend</h3>")
              .AppendLine("            <div class=\"legend-item\">")
              .AppendLine("                <span class=\"legend-box started\"></span>")
              .AppendLine("                <span>Phase Started</span>")
              .AppendLine("            </div>")
