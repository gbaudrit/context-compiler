              .AppendLine("                <span>Phase Completed</span>")
              .AppendLine("            </div>")
              .AppendLine("            <div class=\"legend-item\">")
              .AppendLine("                <span class=\"legend-box failed\"></span>")
              .AppendLine("                <span>Phase Failed</span>")
              .AppendLine("            </div>")
              .AppendLine("        </div>")
              .AppendLine(CultureInfo.InvariantCulture, $"        <div class=\"timestamp\">Generated: {DateTimeOffset.UtcNow:yyyy-MM-dd HH:mm:ss} UTC</div>")
              .AppendLine("    </div>")
              .AppendLine("</body>")
              .AppendLine("</html>");

        return sb.ToString();
    }
}
