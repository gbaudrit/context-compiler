              .AppendLine("            filteredEvents = allEvents.filter(e => {")
              .AppendLine("                if (pipelineFilter && e.PipelineId !== pipelineFilter) return false;")
              .AppendLine("                if (phaseFilter && e.PhaseId !== phaseFilter) return false;")
              .AppendLine("                if (moduleFilter && e.ModuleId !== moduleFilter) return false;")
              .AppendLine("                if (itemFilter && e.ItemId !== itemFilter) return false;")
              .AppendLine("                return true;")
              .AppendLine("            });")
