              .AppendLine("")
              .AppendLine("        function generateDiagram() {")
              .AppendLine("            if (filteredEvents.length === 0) {")
              .AppendLine("                document.getElementById('mermaidDiagram').innerHTML = '<p style=\"text-align:center; color:#999;\">No events match the current filters</p>';")
