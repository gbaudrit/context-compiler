              .AppendLine("                                mermaidCode += `            ${previousEventId} --> ${eventId}\\n`;")
              .AppendLine("                            }")
              .AppendLine("")
              .AppendLine("                            previousEventId = eventId;")
              .AppendLine("                        });")
              .AppendLine("                    }")
              .AppendLine("")
              .AppendLine("                    mermaidCode += '        end\\n';")
              .AppendLine("                }")
              .AppendLine("")
              .AppendLine("                mermaidCode += '    end\\n';")
              .AppendLine("            }")
              .AppendLine("")
              .AppendLine("            addPipelineLinksAndRender(mermaidCode);")
              .AppendLine("        }")
