              .AppendLine("        function addPipelineLinksAndRender(mermaidCode, eventNodeMap = {}, pipelineFirstNodes = {}) {")
              .AppendLine("            // Add pipeline hierarchy links if enabled")
              .AppendLine("            const showPipelineLinks = document.getElementById('showPipelineLinks').checked;")
              .AppendLine("            if (showPipelineLinks) {")
              .AppendLine("                // Build parent-child relationships")
              .AppendLine("                const subPipelines = {};")
              .AppendLine("                filteredEvents.forEach(e => {")
              .AppendLine("                    if (e.ParentPipelineId && !subPipelines[e.PipelineId]) {")
              .AppendLine("                        subPipelines[e.PipelineId] = {")
              .AppendLine("                            parentPipelineId: e.ParentPipelineId,")
              .AppendLine("                            firstEvent: e")
              .AppendLine("                        };")
              .AppendLine("                    }")
              .AppendLine("                });")
              .AppendLine("")
              .AppendLine("                // Create links from parent event to child pipeline")
              .AppendLine("                for (const [childPipelineId, info] of Object.entries(subPipelines)) {")
              .AppendLine("                    const safeChildId = sanitizeId(childPipelineId);")
              .AppendLine("                    const firstChildEvent = info.firstEvent;")
              .AppendLine("                    const childItemKey = firstChildEvent.ItemId || '(global)';")
              .AppendLine("                    const childPipelineCurrentPhaseKey = firstChildEvent.PipelineCurrentPhaseKey;")
              .AppendLine("")
              .AppendLine("                    // Find the parent event that launched this sub-pipeline")
              .AppendLine("                    // The parent event's PhaseId should match the child's PipelineCurrentPhaseKey")
              .AppendLine("                    let parentEvents = filteredEvents")
              .AppendLine("                        .filter(e => ")
              .AppendLine("                            e.PipelineId === info.parentPipelineId &&")
              .AppendLine("                            e.PhaseId === childPipelineCurrentPhaseKey && // Match PhaseId with child's CurrentPhaseKey")
              .AppendLine("                            new Date(e.Timestamp) < new Date(firstChildEvent.Timestamp)")
              .AppendLine("                        )")
              .AppendLine("                        .sort((a, b) => new Date(b.Timestamp) - new Date(a.Timestamp));")
              .AppendLine("                    ")
              .AppendLine("                    // If no exact match found, fallback to last event before child starts")
              .AppendLine("                    if (parentEvents.length === 0) {")
              .AppendLine("                        parentEvents = filteredEvents")
              .AppendLine("                            .filter(e => ")
              .AppendLine("                                e.PipelineId === info.parentPipelineId &&")
              .AppendLine("                                (e.ItemId || '(global)') === childItemKey &&")
              .AppendLine("                                new Date(e.Timestamp) < new Date(firstChildEvent.Timestamp)")
              .AppendLine("                            )")
              .AppendLine("                            .sort((a, b) => new Date(b.Timestamp) - new Date(a.Timestamp));")
              .AppendLine("                        ")
              .AppendLine("                        // If still no match with same ItemId, try global events")
              .AppendLine("                        if (parentEvents.length === 0 && childItemKey !== '(global)') {")
              .AppendLine("                            parentEvents = filteredEvents")
              .AppendLine("                                .filter(e => ")
              .AppendLine("                                    e.PipelineId === info.parentPipelineId &&")
              .AppendLine("                                    !e.ItemId && // Global event (no ItemId)")
              .AppendLine("                                    new Date(e.Timestamp) < new Date(firstChildEvent.Timestamp)")
