              .AppendLine("                                .sort((a, b) => new Date(b.Timestamp) - new Date(a.Timestamp));")
              .AppendLine("                        }")
              .AppendLine("                    }")
              .AppendLine("")
              .AppendLine("                    let parentEventNode = null;")
              .AppendLine("                    ")
