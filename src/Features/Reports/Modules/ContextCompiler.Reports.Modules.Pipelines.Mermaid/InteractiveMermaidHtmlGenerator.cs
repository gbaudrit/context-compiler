              .AppendLine("            const items = [...new Set(allEvents.map(e => e.ItemId).filter(i => i))];")
              .AppendLine("")
              .AppendLine("            const pipelineSelect = document.getElementById('pipelineFilter');")
              .AppendLine("            pipelines.forEach(p => {")
              .AppendLine("                const option = document.createElement('option');")
              .AppendLine("                option.value = p;")
              .AppendLine("                option.textContent = p;")
              .AppendLine("                pipelineSelect.appendChild(option);")
              .AppendLine("            });")
              .AppendLine("")
              .AppendLine("            const phaseSelect = document.getElementById('phaseFilter');")
              .AppendLine("            phases.forEach(p => {")
              .AppendLine("                const option = document.createElement('option');")
              .AppendLine("                option.value = p;")
              .AppendLine("                option.textContent = p;")
              .AppendLine("                phaseSelect.appendChild(option);")
              .AppendLine("            });")
              .AppendLine("")
              .AppendLine("            const moduleSelect = document.getElementById('moduleFilter');")
              .AppendLine("            modules.forEach(m => {")
              .AppendLine("                const option = document.createElement('option');")
              .AppendLine("                option.value = m;")
              .AppendLine("                option.textContent = m;")
